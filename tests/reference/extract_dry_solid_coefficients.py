"""Extract the dry subset of the audited MELTS site transcription.

This changes representation only. Regenerate the original parameter file
with examples/m2_solid_mixing/transcribe_*.py to re-audit source equations.
No source strings are executed, and no native runtime is redistributed.
"""

import hashlib
import json
from pathlib import Path
from pprint import pformat

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT/'examples/m2_solid_mixing/parameters.json'
DESTINATION = ROOT/'src/exoeos/magma_solids/_coefficients.py'
PHASES = ('alkali-feldspar', 'plagioclase', 'spinel', 'rhm-oxide',
          'clinopyroxene', 'orthopyroxene')


def compact(data):
    return {'size': len(data['coordinate_bounds']),
            **{k: data[k+'_polynomial'] for k in ('H', 'S', 'V')},
            'sites': [(s['multiplicity'], s['polynomial']) for s in data['entropy_sites']]}


def render():
    data = json.loads(SOURCE.read_text())
    lines = ['"""Pinned site coefficients; generated by tests/reference/extract_dry_solid_coefficients.py."""',
             '', '# Source parameter SHA256: '+hashlib.sha256(SOURCE.read_bytes()).hexdigest(), '']
    for phase in PHASES:
        d = data['models'][phase]
        name = phase.upper().replace('-', '_')
        lines.append('# '+d['source_file']+' SHA256: '+d['source_sha256'])
        lines.append(name+' = '+pformat(compact(d), width=100, sort_dicts=False))
        if 'pure_reference_models' in d:
            lines.append(name+'_REFERENCES = '+pformat([compact(r) for r in d['pure_reference_models']],
                                                       width=100, sort_dicts=False))
        lines.append('')
    return '\n'.join(lines)


if __name__ == '__main__':
    DESTINATION.write_text(render())
